/**
 * Owner review pages: docs/content/review/<topicId>.md
 *
 * Rendered from the topic JSON (what the app will show) plus the provenance map (page per item).
 * The first line carries a hash of the generated text. If the file on disk no longer matches its
 * hash, a human has edited it (ticked boxes, wrote findings) and it is NOT overwritten unless forced.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { sessionLabel } from "./source.ts";
import type { ProvenanceMap } from "./build.ts";
import type { Keyword, QuestionSection, SiriCheck, Theme, TopicFile } from "@/lib/content/schema/authoring";
import type { CorrectionNote, MarginNote } from "./pipeline-schema.ts";

const HASH_PLACEHOLDER = "HASH";
const HEADER_RE = /^<!-- GENERATED by scripts\/content\/(?:extract|build-pilot)\.ts\. hash:([0-9a-f]+|HASH) -->/;

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

const da = (s: string) => `<div lang="da" dir="ltr">${esc(s)}</div>`;
const fa = (s: string) => `<div lang="fa" dir="rtl">${esc(s)}</div>`;
const daInline = (s: string) => `<bdi lang="da" dir="ltr">${esc(s)}</bdi>`;
const faInline = (s: string) => `<bdi lang="fa" dir="rtl">${esc(s)}</bdi>`;

function emphasised(text: string, ranges: Array<{ start: number; end: number }>): string {
  let out = "";
  let last = 0;
  for (const r of ranges) {
    out += esc(text.slice(last, r.start)) + "<strong>" + esc(text.slice(r.start, r.end)) + "</strong>";
    last = r.end;
  }
  return `<div lang="da" dir="ltr">${out + esc(text.slice(last))}</div>`;
}

const NOTE_LABEL: Record<MarginNote["kind"], string> = {
  recurring: "🔁 recurring",
  related: "🔗 related",
  tip: "📌 tip",
  highlight: "⭐ highlight",
  nursing: "🩺 nursing",
};

export function renderReviewPage(
  topic: TopicFile,
  prov: ProvenanceMap,
  theme: Theme,
  marginNotes: MarginNote[],
  sources: Map<string, string>,
  corrections: CorrectionNote[],
): string {
  const L: string[] = [];
  const p = (path: string) => {
    const e = prov[path];
    if (!e) throw new Error(`${topic.id}: no provenance for ${path}`);
    return `p. ${e.page}`;
  };
  const item = (title: string, id: string | null, page: string) => L.push(`- [ ] **${title}**${id ? ` · \`${id}\`` : ""} · ${page}`, "");
  const block = (...html: string[]) => {
    for (const h of html) L.push(h, "");
  };
  const siriLine = (c: SiriCheck): void => {
    if (c.status === "unchecked") {
      L.push("SIRI wording check: *not checked* (no public SIRI examiner booklet found for this term).", "");
      return;
    }
    const where = `${c.sourceDisplay?.title ?? c.sourceRef!.document}, p. ${c.sourceRef!.pages.join(", ")}; ${c.sourceDisplay?.note ?? ""} checked ${c.checkedOn}`;
    if (c.status === "matches") {
      L.push(`SIRI wording check: **matches** (${where})${c.siriParts!.length > 1 ? `; SIRI prints it as ${c.siriParts!.length} quoted parts` : ""}.`, "");
    } else {
      L.push(`SIRI wording check: **DIFFERS** (${where}). SIRI's wording, kept alongside (the booklet text above is not changed):`, "");
      block(da(c.siriParts!.join(" ")));
    }
  };

  const termMatch = /^(\d{4})-(maj|nov)$/.exec(topic.termId);
  if (!termMatch) throw new Error(`${topic.id}: bad termId ${topic.termId}`);
  const termYear = termMatch[1]!;
  const termSession = termMatch[2] === "maj" ? "maj" : "nov";
  const sub = topic.subthemeId ? theme.subthemes.find((s) => s.id === topic.subthemeId) : undefined;
  L.push(`<!-- GENERATED by scripts/content/extract.ts. hash:${HASH_PLACEHOLDER} -->`, "");
  L.push(`# Review: ${topic.id} · ${esc(topic.title.da!)}`, "");
  L.push("| | |", "|---|---|");
  L.push(`| **Term** | ${sessionLabel(termSession)} ${termYear} · Emne ${topic.letter} |`);
  L.push(`| **Theme** | ${esc(theme.title.da!)} · ${faInline(theme.title.fa!)}${sub ? ` / ${esc(sub.title.da!)} · ${faInline(sub.title.fa!)}` : ""} |`);
  L.push(`| **Booklet PDF pages** | ${topic.source.pages.join(", ")} |`);
  L.push(`| **Review status** | \`${topic.review.status}\`${topic.review.reviewedBy ? ` by \`${topic.review.reviewedBy}\` on ${topic.review.reviewedOn ?? "?"}` : ""} |`);
  L.push(`| **Generated from** | \`content/topics/${topic.id}.json\` |`);
  const refs = [
    ...topic.situations.flatMap((s) => (s.intro?.sourceRef ? [s.intro.sourceRef.document] : [])),
    ...[...topic.situations, topic.general].flatMap((s) => [s.question.siriCheck, ...s.followups.map((f) => f.siriCheck)].flatMap((c) => (c.sourceRef ? [c.sourceRef.document] : []))),
  ];
  const used = [...new Set(refs)];
  if (used.length) L.push(`| **SIRI source** | ${used.map((d) => `\`${d}\`: ${esc(sources.get(d) ?? d)}`).join("; ")} |`);
  L.push("");
  L.push("## How to review", "");
  L.push("1. Open `docs/resources/PD3_Mundtlig_Delproeve2.pdf` at the page given for each item.");
  L.push("2. **Persian (main task):** does each Persian line say exactly what the PDF says? Check every word, half-space (ZWNJ) and punctuation mark. The Persian has not been machine-checked against the PDF.");
  L.push("3. **Danish:** it was machine-checked against the booklet PDF and, for May–June 2024, against SIRI's examiner booklet. A quick glance is enough.");
  L.push("4. **Completeness:** is anything on these pages missing here?");
  L.push("5. Tick `[x]` when an item is right. Write any problem under **Findings** at the end, with the item ID. Don't edit the text itself here: corrections are recorded in the pipeline, next to the original.");
  L.push("");
  L.push("Once you edit this file, the build stops regenerating it, so your ticks are safe.", "");

  if (topic.review.notes?.length) {
    L.push("## Notes from the extraction (please read first)", "");
    for (const n of topic.review.notes) L.push(`- ${n.path ? `\`${n.path}\`` : "topic"}${n.pages?.length ? ` (p. ${n.pages.join(", ")})` : ""}: ${esc(n.text)}`);
    L.push("");
  }

  L.push(`## Topic · ${p("title")}`, "");
  item("Topic title", topic.id, p("title"));
  block(da(topic.title.da!), fa(topic.title.fa!));
  L.push(`### The two situations`, "");
  topic.situations.forEach((s, i) => {
    item(`Situation ${s.key}: title (booklet)`, s.id, p(`situations[${i}].title`));
    block(da(s.title.da!), fa(s.title.fa!));
  });

  const section = (s: QuestionSection, path: string, heading: string, intro?: TopicFile["situations"][number]["intro"]) => {
    L.push(`## ${heading} · ${p(`${path}.question.text.da`)}`, "");
    if (intro) {
      const from = intro.origin === "siri" ? `SIRI "Forslag til indledning", verbatim; ${intro.sourceRef!.document} p. ${intro.sourceRef!.pages.join(", ")}` : "WRITTEN FOR THE APP from the booklet title";
      item(`Examiner's introduction of the situation (${from}; not in the booklet, no Persian; status \`${intro.review.status}\`)`, intro.id, intro.origin === "siri" ? "SIRI" : "app");
      block(da(intro.text.da!));
    }
    const q = s.question;
    item("Required question (Danish, as printed in the booklet)", q.id, p(`${path}.question.text.da`));
    block(da(q.text.da!));
    siriLine(q.siriCheck);
    item("Persian translation of the question", null, p(`${path}.question.text.fa`));
    block(fa(q.text.fa!));
    L.push("Key words:", "");
    q.keywords.forEach((k: Keyword, i: number) => {
      L.push(`- [ ] ${k.emoji} ${daInline(k.text.da!)} = ${faInline(k.text.fa!)} · \`${k.id}\` · ${p(`${path}.question.keywords[${i}]`)}`);
    });
    L.push("");
    item("Model answer (Danish only; bold = template connectives)", q.modelAnswer.id, p(`${path}.question.modelAnswer`));
    block(emphasised(q.modelAnswer.text.da!, q.modelAnswer.emphasis));
    s.followups.forEach((f, i) => {
      L.push(`### Suggested follow-up ${i + 1} (forslag til opfølgende spørgsmål) · ${p(`${path}.followups[${i}].text.da`)}`, "");
      item("Suggested follow-up (Danish, as printed in the booklet)", f.id, p(`${path}.followups[${i}].text.da`));
      block(da(f.text.da!));
      siriLine(f.siriCheck);
      if (f.spoken) L.push(`Examiner voice (app, not displayed): ${f.spoken.parts.map((x) => `*${esc(x)}*`).join(` · pause ${f.spoken.pauseMs} ms · `)}`, "");
      item("Persian translation of the follow-up", null, p(`${path}.followups[${i}].text.fa`));
      block(fa(f.text.fa!));
      item("Short answer (Danish only)", f.answer.id, p(`${path}.followups[${i}].answer`));
      block(da(f.answer.text.da!));
    });
    s.personalExamples.forEach((e, i) => {
      item(`Personal example (label: ${e.label.fa})`, e.id, p(`${path}.personalExamples[${i}]`));
      block(da(e.text.da!));
    });
  };
  topic.situations.forEach((s, i) => {
    section(s, `situations[${i}]`, `Situation ${s.key}: first required question`, s.intro);
  });
  section(topic.general, "general", "General question: second required question");

  if (marginNotes.length) {
    L.push("## Margin notes (internal: NOT shown in the app)", "");
    L.push("Stored in `content/internal/margin-notes.json`. A note can only become public after it is reviewed and approved on its own, and never if it has a confidentiality hit.", "");
    for (const n of marginNotes) {
      const extra = [n.sectionId ? `inside ${n.sectionId}` : "", n.refs.length ? `refers to ${n.refs.join(", ")}` : "", n.confidentialityHits.length ? `CONFIDENTIALITY HIT (${n.confidentialityHits.join(", ")}), must stay internal` : ""].filter(Boolean).join("; ");
      item(`Margin note (${NOTE_LABEL[n.kind]})${extra ? `, ${extra}` : ""}`, n.id, p(`marginNotes:${n.id}`));
      block(fa(n.text.fa!));
    }
  }

  if (corrections.length) {
    L.push("## Correction notes (kept next to the booklet text, never applied)", "");
    for (const c of corrections) L.push(`- \`${c.id}\` (${c.kind}, ${c.status}) \`${c.path}\`: «${esc(c.find)}» → «${esc(c.suggestion)}». ${esc(c.reason)} (${esc(c.by)}, ${esc(c.source)})`);
    L.push("");
  }

  L.push("## Findings", "");
  L.push("<!-- Write problems here, one per line, starting with the item ID. Example: `2024-maj-a.sitA.q1` Persian: … -->", "");
  return L.join("\n").replace(/\n{3,}/g, "\n\n") + "\n";
}

function hashOf(text: string): string {
  return createHash("sha256").update(text).digest("hex").slice(0, 16);
}

/** Write the review page unless a human has edited the existing one. Returns what happened. */
export function writeReviewPage(path: string, body: string, force: boolean): "written" | "unchanged" | "kept-human-edits" {
  const withHash = body.replace(`hash:${HASH_PLACEHOLDER}`, `hash:${hashOf(body)}`);
  if (existsSync(path)) {
    const current = readFileSync(path, "utf8");
    if (current === withHash) return "unchanged";
    const m = HEADER_RE.exec(current);
    const untouched = m && m[1] === hashOf(current.replace(HEADER_RE, (h) => h.replace(m[1]!, HASH_PLACEHOLDER)));
    if (!untouched && !force) return "kept-human-edits";
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, withHash);
  return "written";
}
