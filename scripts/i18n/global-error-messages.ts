/**
 * Writes src/app/global-error-messages.ts from the `error` namespace of the default locale's
 * messages file. global-error.tsx is a client component in every page's bundle, so it imports
 * these two strings instead of the whole messages file (ADR-0014 budget). messages/fa.json stays
 * the source; src/app/global-error.test.tsx fails when the generated module is out of date.
 *
 * Run: npm run i18n:global-error
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import messages from "../../messages/fa.json" with { type: "json" };

const target = fileURLToPath(new URL("../../src/app/global-error-messages.ts", import.meta.url));
const { title, retry } = messages.error;

writeFileSync(
  target,
  `// Generated by scripts/i18n/global-error-messages.ts from messages/fa.json (error namespace).
// Don't edit by hand: change messages/fa.json and run \`npm run i18n:global-error\`.
export const globalErrorMessages = {
  title: ${JSON.stringify(title)},
  retry: ${JSON.stringify(retry)},
};
`,
);
console.log(`Wrote ${target}`);
